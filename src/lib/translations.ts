// Helper function to get translations in library files (without React context)
export function getTranslations(): typeof translations.pt {
  if (typeof window === 'undefined') return translations.pt
  const saved = localStorage.getItem('padel1_language') as Language | null
  const lang: Language = (saved && (saved === 'pt' || saved === 'en' || saved === 'es' || saved === 'fr')) ? saved : 'pt'
  return translations[lang]
}
